/* =========================================================
   لوحة «مؤشرات لقاءات» – interaction logic
   Data:  data/regions.js  (window.LIQAAT_DATA)
   Map:   data/map-data.js (window.LIQAAT_MAP, generated by tools/build-map.py)
   ========================================================= */
(function () {
  "use strict";

  const DATA = window.LIQAAT_DATA;
  const MAP = window.LIQAAT_MAP;
  const ICONS = window.LIQAAT_ICONS;
  const NS = "http://www.w3.org/2000/svg";

  /* Base tone of each region on the map (subtle variation as in the reference) */
  const REGION_TONES = {
    "tabuk": "#174670",
    "jawf": "#134068",
    "northern-borders": "#16446c",
    "hail": "#0c2f60",
    "qassim": "#15416a",
    "madinah": "#0e3164",
    "makkah": "#113766",
    "riyadh": "#133f69",
    "eastern": "#174a72",
    "bahah": "#15436c",
    "asir": "#0c2e62",
    "jazan": "#15426b",
    "najran": "#16466f"
  };

  const COUNT_MS = 600;
  const numberFmt = new Intl.NumberFormat("en-US");

  const $ = (sel, root = document) => root.querySelector(sel);
  const $$ = (sel, root = document) => Array.from(root.querySelectorAll(sel));
  const svgEl = (tag, attrs = {}, parent) => {
    const el = document.createElementNS(NS, tag);
    for (const k in attrs) el.setAttribute(k, attrs[k]);
    if (parent) parent.appendChild(el);
    return el;
  };
  const escapeHtml = (s) =>
    String(s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));

  const regionIds = Object.keys(DATA.regions);
  const state = { active: null, countTimers: new Map() };
  const refs = { paths: {}, labels: {}, buttons: {} };

  /* ---------- Stage scaling (keeps the 1920×1080 composition on any screen) ---------- */
  function fitStage() {
    const s = Math.min(window.innerWidth / 1920, window.innerHeight / 1080);
    document.documentElement.style.setProperty("--scale", s.toFixed(5));
  }

  /* ---------- Map ---------- */
  function buildMap() {
    const svg = $("#mapSvg");
    const [vx, vy, vw, vh] = MAP.viewBox;
    svg.setAttribute("viewBox", `${vx} ${vy} ${vw} ${vh}`);

    const defs = svgEl("defs", {}, svg);
    defs.innerHTML = `
      <linearGradient id="gradActive" x1="0" y1="0" x2="0.35" y2="1">
        <stop offset="0" stop-color="#22d39a" stop-opacity=".92"/>
        <stop offset=".55" stop-color="#0fa877" stop-opacity=".9"/>
        <stop offset="1" stop-color="#0a7f5f" stop-opacity=".92"/>
      </linearGradient>
      <linearGradient id="gradLight" x1="0" y1="0" x2="1" y2="1">
        <stop offset="0" stop-color="#9fd8ff" stop-opacity=".10"/>
        <stop offset=".5" stop-color="#9fd8ff" stop-opacity="0"/>
        <stop offset="1" stop-color="#000814" stop-opacity=".22"/>
      </linearGradient>
      <pattern id="patDots" width="7" height="7" patternUnits="userSpaceOnUse">
        <circle cx="1.2" cy="1.2" r=".65" fill="#8fd3ff" fill-opacity=".16"/>
      </pattern>
      <pattern id="patGrid" width="46" height="46" patternUnits="userSpaceOnUse">
        <path d="M46 0H0V46" fill="none" stroke="#7cc8ff" stroke-opacity=".07" stroke-width="1"/>
      </pattern>
      <filter id="fGlowGreen" x="-30%" y="-30%" width="160%" height="160%">
        <feGaussianBlur in="SourceGraphic" stdDeviation="3.2" result="b"/>
        <feMerge><feMergeNode in="b"/><feMergeNode in="b"/><feMergeNode in="SourceGraphic"/></feMerge>
      </filter>
      <filter id="fGlowSky" x="-30%" y="-30%" width="160%" height="160%">
        <feGaussianBlur in="SourceGraphic" stdDeviation="2.4" result="b"/>
        <feMerge><feMergeNode in="b"/><feMergeNode in="SourceGraphic"/></feMerge>
      </filter>
      <filter id="fBlurWide" x="-10%" y="-10%" width="120%" height="120%">
        <feGaussianBlur stdDeviation="9"/>
      </filter>
      <filter id="fBlurSoft" x="-10%" y="-10%" width="120%" height="120%">
        <feGaussianBlur stdDeviation="1.4"/>
      </filter>`;

    // Silhouette = every region path, unstyled; reused for walls, glow, outline and clipping
    const sil = svgEl("g", { id: "silhouette" }, defs);
    const clip = svgEl("clipPath", { id: "clipCountry" }, defs);
    regionIds.forEach((id) => {
      const geo = MAP.regions[id];
      svgEl("path", { d: geo.d }, sil);
      svgEl("path", { d: geo.d }, clip);
    });

    // 3D extrusion (stacked silhouettes, darker toward the base)
    const walls = svgEl("g", { "aria-hidden": "true" }, svg);
    const depth = 22;
    const off = (i) => `translate(${(-i * 0.55).toFixed(2)} ${(i * 1.45).toFixed(2)})`;
    for (let i = depth; i >= 1; i--) {
      const t = i / depth;
      const c = `rgb(${Math.round(6 + 16 * (1 - t))}, ${Math.round(22 + 40 * (1 - t))}, ${Math.round(40 + 52 * (1 - t))})`;
      svgEl("use", { href: "#silhouette", transform: off(i), fill: c }, walls);
    }
    svgEl("use", {
      href: "#silhouette", transform: off(depth), fill: "none",
      stroke: "#3fb6ff", "stroke-opacity": ".35", "stroke-width": "1.2"
    }, walls);

    // Outer glow + coastline lights + bright outline (regions on top hide the inner half)
    const edge = svgEl("g", { "aria-hidden": "true" }, svg);
    svgEl("use", { href: "#silhouette", fill: "none", stroke: "#2fa8ff", "stroke-width": "14", "stroke-opacity": ".55", filter: "url(#fBlurWide)", class: "outline-pulse" }, edge);
    svgEl("use", { href: "#silhouette", fill: "none", stroke: "#ffb46a", "stroke-width": "6", "stroke-opacity": ".55", "stroke-dasharray": "1 6", "stroke-linecap": "round", filter: "url(#fBlurSoft)" }, edge);
    svgEl("use", { href: "#silhouette", fill: "none", stroke: "#8fe6ff", "stroke-width": "3.4", class: "outline-pulse" }, edge);

    // Interactive regions
    const gRegions = svgEl("g", { class: "regions" }, svg);
    regionIds.forEach((id) => {
      const r = DATA.regions[id];
      const p = svgEl("path", {
        d: MAP.regions[id].d,
        class: "region",
        fill: REGION_TONES[id] || "#164470",
        tabindex: "0",
        role: "button",
        "aria-label": r.name,
        "data-id": id
      }, gRegions);
      refs.paths[id] = p;
    });

    // Technical texture + lighting, clipped to the country, never intercepting clicks
    const tex = svgEl("g", { "clip-path": "url(#clipCountry)", "pointer-events": "none", "aria-hidden": "true" }, svg);
    svgEl("rect", { x: vx, y: vy, width: vw, height: vh, fill: "url(#patGrid)" }, tex);
    svgEl("rect", { x: vx, y: vy, width: vw, height: vh, fill: "url(#patDots)", opacity: ".55" }, tex);
    svgEl("rect", { x: vx, y: vy, width: vw, height: vh, fill: "url(#gradLight)" }, tex);
    addCityLights(tex, vw, vh);

    // Hover + active highlight overlays
    refs.hover = svgEl("path", { class: "map-glow-hover", d: "" }, svg);
    refs.activeGlow = svgEl("path", { class: "map-glow-active", d: "" }, svg);

    // Labels (pin + name)
    const gLabels = svgEl("g", { class: "labels" }, svg);
    regionIds.forEach((id) => {
      const [x, y] = MAP.regions[id].label;
      const g = svgEl("g", { class: "map-label", "data-id": id }, gLabels);
      const pin = svgEl("g", { class: "pin" }, g);
      pin.innerHTML =
        '<path d="M20 10c0 4.993-5.539 10.193-7.399 11.799a1 1 0 0 1-1.202 0C9.539 20.193 4 14.993 4 10a8 8 0 0 1 16 0" fill="rgba(4,24,44,.35)" stroke="currentColor" stroke-width="2.2"/>' +
        '<circle cx="12" cy="10" r="3" fill="none" stroke="currentColor" stroke-width="2.2"/>';
      const text = svgEl("text", { x: x, y: y + 13 }, g);
      text.textContent = DATA.regions[id].name;
      refs.labels[id] = { g, pin, text, x, y };
      placePin(id, false);
    });

    // Events (delegated)
    svg.addEventListener("click", (e) => {
      const t = e.target.closest("[data-id]");
      if (t) select(t.getAttribute("data-id"));
    });
    svg.addEventListener("keydown", (e) => {
      if ((e.key === "Enter" || e.key === " ") && e.target.matches(".region")) {
        e.preventDefault();
        select(e.target.getAttribute("data-id"));
      }
    });
    svg.addEventListener("pointerover", (e) => {
      const t = e.target.closest("[data-id]");
      setHover(t ? t.getAttribute("data-id") : null);
    });
    svg.addEventListener("pointerleave", () => setHover(null));
  }

  function placePin(id, active) {
    const L = refs.labels[id];
    const s = active ? 1.5 : 1;
    const tx = L.x - 12 * s;
    const ty = L.y - 6 - 22 * s;
    L.pin.style.transform = `translate(${tx}px, ${ty}px) scale(${s})`;
    L.text.setAttribute("y", active ? L.y + 17 : L.y + 13);
  }

  function addCityLights(parent, w, h) {
    let seed = 7331;
    const rnd = () => ((seed = (seed * 1103515245 + 12345) >>> 0) / 4294967296);
    // a few warm clusters roughly at major population centres (decorative only)
    const clusters = [
      [478, 417, 26, 70], [232, 445, 22, 50], [255, 470, 14, 30], [232, 372, 16, 34],
      [770, 330, 22, 50], [740, 360, 14, 26], [385, 280, 14, 26], [362, 590, 14, 28],
      [120, 190, 10, 18], [300, 222, 10, 18], [352, 680, 10, 16], [505, 640, 10, 14]
    ];
    const g = svgEl("g", { opacity: ".75" }, parent);
    let html = "";
    clusters.forEach(([cx, cy, spread, n]) => {
      for (let i = 0; i < n; i++) {
        const a = rnd() * Math.PI * 2;
        const r = Math.pow(rnd(), 1.6) * spread;
        const x = cx + Math.cos(a) * r, y = cy + Math.sin(a) * r;
        const op = (0.25 + rnd() * 0.6).toFixed(2);
        html += `<circle cx="${x.toFixed(1)}" cy="${y.toFixed(1)}" r="${(0.4 + rnd() * 0.8).toFixed(2)}" fill="#ffd29a" fill-opacity="${op}"/>`;
      }
    });
    // sparse scattered lights
    for (let i = 0; i < 260; i++) {
      html += `<circle cx="${(rnd() * w).toFixed(1)}" cy="${(rnd() * h).toFixed(1)}" r=".5" fill="#ffe0b0" fill-opacity="${(0.15 + rnd() * 0.4).toFixed(2)}"/>`;
    }
    g.innerHTML = html;
  }

  function setHover(id) {
    $$(".regionbar button").forEach((b) => b.classList.toggle("is-hover", b.dataset.id === id));
    if (!id || id === state.active) {
      refs.hover.classList.remove("is-on");
      return;
    }
    refs.hover.setAttribute("d", MAP.regions[id].d);
    refs.hover.classList.add("is-on");
  }

  /* ---------- Region bar ---------- */
  function buildRegionBar() {
    const bar = $("#regionBar");
    regionIds.forEach((id) => {
      const b = document.createElement("button");
      b.type = "button";
      b.dataset.id = id;
      b.textContent = DATA.regions[id].name;
      b.setAttribute("aria-pressed", "false");
      b.addEventListener("click", () => select(id));
      b.addEventListener("pointerenter", () => setHover(id));
      b.addEventListener("pointerleave", () => setHover(null));
      bar.appendChild(b);
      refs.buttons[id] = b;
    });
  }

  /* ---------- Panel rendering ---------- */
  function replay(el) {
    el.classList.remove("is-swapping");
    void el.offsetWidth; // restart CSS animation
    el.classList.add("is-swapping");
  }

  function countTo(el, target) {
    const prev = state.countTimers.get(el);
    if (prev) cancelAnimationFrame(prev);
    const start = performance.now();
    const step = (now) => {
      const t = Math.min(1, (now - start) / COUNT_MS);
      const eased = 1 - Math.pow(1 - t, 3);
      el.textContent = numberFmt.format(Math.round(target * eased));
      if (t < 1) state.countTimers.set(el, requestAnimationFrame(step));
      else state.countTimers.delete(el);
    };
    state.countTimers.set(el, requestAnimationFrame(step));
  }

  function renderPanel(id) {
    const r = DATA.regions[id];

    const title = $("#panelTitle");
    title.textContent = r.title || "منطقة " + r.name;
    replay(title);

    const sky = $("#panelSky");
    sky.innerHTML = r.headerImage ? `<img src="${escapeHtml(r.headerImage)}" alt="">` : "";

    $$(".stat__value").forEach((el) => countTo(el, Number(r[el.dataset.key]) || 0));

    const sectors = $("#sectors");
    sectors.innerHTML = (r.sectors || [])
      .slice(0, 5)
      .map((name) => {
        const icon = (DATA.sectorIcons && DATA.sectorIcons[name]) || "sector";
        return `<div class="sector">${ICONS.svg(icon)}<span>${escapeHtml(name)}</span></div>`;
      })
      .join("");
    replay(sectors);

    const venues = $("#venues");
    const list = (r.venues || []).slice(0, 4);
    venues.innerHTML = list.length
      ? list
          .map(
            (v) =>
              `<figure class="venue" style="margin:0"><img src="${escapeHtml(v.image)}" alt="${escapeHtml(v.name)}" loading="eager"><span title="${escapeHtml(v.name)}">${escapeHtml(v.name)}</span></figure>`
          )
          .join("")
      : `<div class="venues__empty">لا توجد مواقع مضافة لهذه المنطقة</div>`;
    replay(venues);
  }

  /* ---------- Selection (shared by map + bar) ---------- */
  function select(id) {
    if (!DATA.regions[id] || id === state.active) return;
    const prev = state.active;
    state.active = id;

    if (prev) {
      refs.paths[prev].classList.remove("is-active");
      refs.labels[prev].g.classList.remove("is-active");
      placePin(prev, false);
      refs.buttons[prev].classList.remove("is-active");
      refs.buttons[prev].setAttribute("aria-pressed", "false");
    }
    refs.paths[id].classList.add("is-active");
    refs.labels[id].g.classList.add("is-active");
    // keep the active label above its neighbours
    refs.labels[id].g.parentNode.appendChild(refs.labels[id].g);
    placePin(id, true);
    refs.buttons[id].classList.add("is-active");
    refs.buttons[id].setAttribute("aria-pressed", "true");

    const glow = refs.activeGlow;
    glow.classList.remove("is-on");
    glow.setAttribute("d", MAP.regions[id].d);
    void glow.getBoundingClientRect();
    glow.classList.add("is-on");
    refs.hover.classList.remove("is-on");

    renderPanel(id);
  }

  /* ---------- Fullscreen ---------- */
  function setupFullscreen() {
    const btn = $("#fsBtn");
    const sync = () => {
      const on = !!document.fullscreenElement;
      btn.innerHTML = ICONS.svg(on ? "minimize" : "maximize");
      btn.setAttribute("aria-label", on ? "إنهاء ملء الشاشة" : "ملء الشاشة");
    };
    const toggle = () => {
      if (document.fullscreenElement) document.exitFullscreen();
      else document.documentElement.requestFullscreen().catch(() => {});
    };
    btn.addEventListener("click", toggle);
    document.addEventListener("fullscreenchange", sync);
    document.addEventListener("keydown", (e) => {
      if (e.target.closest && e.target.closest("input, textarea")) return;
      if (e.key === "f" || e.key === "F") toggle();
      // ← / → cycle through regions (presentation remote friendly)
      if (e.key === "ArrowLeft" || e.key === "ArrowRight") {
        const i = regionIds.indexOf(state.active);
        const d = e.key === "ArrowLeft" ? 1 : -1; // RTL: left = next
        select(regionIds[(i + d + regionIds.length) % regionIds.length]);
      }
    });
    sync();
  }

  /* ---------- Init ---------- */
  function init() {
    fitStage();
    window.addEventListener("resize", fitStage);

    $$("[data-icon]").forEach((el) => (el.innerHTML = ICONS.svg(el.dataset.icon)));
    $("#panelPin").innerHTML = ICONS.svg("pin");

    if (DATA.meta && DATA.meta.isDemo) {
      const n = $("#demoNotice");
      n.textContent = DATA.meta.demoNotice || "بيانات تجريبية";
      n.hidden = false;
    }

    buildMap();
    buildRegionBar();
    setupFullscreen();
    select((DATA.meta && DATA.meta.defaultRegion) || regionIds[0]);
  }

  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", init);
  else init();
})();
